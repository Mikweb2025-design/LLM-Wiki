export function t(lang, path) {
  const parts = path.split('.');
  let cur = dict[lang] || dict.en;
  for (const p of parts) {
    if (cur && typeof cur === 'object' && p in cur) cur = cur[p];
    else return path;
  }
  return typeof cur === 'string' ? cur : path;
}

export const I18nContext = createContext({ lang: 'it', setLang: () => {}, t: (p) => p });

export function useI18n() {
  return useContext(I18nContext);
}

export function getInitialLang() {
  const saved = typeof localStorage !== 'undefined' ? localStorage.getItem('llmwiki_lang') : null;
  if (saved && dict[saved]) return saved;
  const nav = typeof navigator !== 'undefined' ? navigator.language.slice(0, 2) : 'it';
  return dict[nav] ? nav : 'en';
}

